"""Generate the editable MoLab (marimo) notebook from walkthrough.py.

    python make_molab.py [OUT.py]

Same steps, explanations and code as the page's Code tab, so the two cannot drift apart. MoLab opens one
file from GitHub with no repository checkout, so cases.py and props_data.py are embedded in the setup cell.
marimo needs each global defined in exactly one cell: the step cells may only define _private names
(checked here).
"""
import ast
import os
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import walkthrough  # noqa: E402

PAGE_URL = "https://chetools.github.io/claude/ai-failure-modes/"


def public_defs(code):
    """Top-level names a cell defines that marimo would treat as globals (not starting with _)."""
    names = set()
    for node in ast.parse(code).body:
        for t in ast.walk(node):
            if isinstance(t, ast.Name) and isinstance(t.ctx, ast.Store) and not t.id.startswith("_"):
                names.add(t.id)
            if isinstance(t, (ast.FunctionDef, ast.Lambda, ast.ListComp, ast.GeneratorExp)):
                break
    return names


def cell(body, args, returns):
    ret = "return" if not returns else "return (" + ", ".join(sorted(returns)) + ",)"
    return f"@app.cell\ndef _({', '.join(sorted(args))}):\n{textwrap.indent(body, '    ')}\n    {ret}\n\n\n"


def md_cell(text):
    assert '"""' not in text
    return cell(f'mo.md(r"""\n{text.strip()}\n""")', ["mo"], [])


def last_expr_to_value(code):
    """marimo shows a cell's last expression; report(...) returns the figure, so keep it last."""
    lines = code.strip("\n").splitlines()
    if not lines[-1].startswith("report("):
        raise ValueError("each step must end with report(...)")
    return "\n".join(lines)


def generate():
    srcs = {m: open(os.path.join(HERE, f"{m}.py"), encoding="utf-8").read() for m in ("props_data", "cases")}
    for s in srcs.values():
        assert "'''" not in s
    out = ['# /// script\n# requires-python = ">=3.10"\n# dependencies = ["marimo", "plotly"]\n# ///\n\n'
           '"""Where an AI gets chemical engineering wrong: ten worked cases, step by step.\n\n'
           f"Editable companion to {PAGE_URL}\n"
           "GENERATED by ai-failure-modes/python/make_molab.py from walkthrough.py, cases.py and props_data.py;\n"
           "edit those files, not this one. Self-contained because MoLab opens a single file from GitHub.\n"
           '"""\n\nimport marimo\n\n__generated_with = "0.25.1"\napp = marimo.App(width="medium")\n\n\n']
    out.append(md_cell(f"""
# Where an AI gets chemical engineering wrong: ten cases, step by step

Editable companion to the [interactive page]({PAGE_URL}). Each step shows the key equations of one case,
computes the **naive** answer (the setup that is easy to get wrong) and the **corrected** one, and plots both
over one input.

**To run:** run all cells once after opening. **To experiment:** edit a value in the `INPUTS` cell and re-run.

The reference module `cases` (and its CoolProp-generated property tables `props_data`) is embedded in the next cell.
"""))
    setup = ["# Setup: plotting, and the reference modules props_data and cases (embedded sources).",
             "import sys as _sys", "import types as _types", "", "import marimo as mo",
             "import plotly.graph_objects as go", ""]
    for m, s in srcs.items():
        setup += [f"_{m.upper()}_SOURCE = r'''{s}'''",
                  f'_m = _types.ModuleType("{m}")', f"_sys.modules['{m}'] = _m",
                  f'exec(compile(_{m.upper()}_SOURCE, "{m}.py", "exec"), _m.__dict__)', ""]
    setup += ["import cases", "", "",
              "def figure(traces, **layout):",
              '    """Plotly figure from trace dicts and layout keywords."""',
              '    layout.setdefault("height", 360)',
              "    return go.Figure(dict(data=traces, layout=layout))", "",
              walkthrough.SETUP.strip("\n")]
    out.append(cell("\n".join(setup), [], ["cases", "figure", "go", "mo", "report"]))

    lines = ["# Inputs of every case (units in the names). Edit a value and re-run.", "INPUTS = {"]
    for cid, kw in walkthrough.INPUTS.items():
        lines.append(f"    {cid!r}: dict(" + ", ".join(f"{k}={v!r}" for k, v in kw.items()) + "),")
    lines.append("}")
    out.append(cell("\n".join(lines), [], ["INPUTS"]))

    for i, c in enumerate(walkthrough.CELLS):
        code = last_expr_to_value(c["code"])
        bad = public_defs(code)
        if bad:
            raise ValueError(f"step {i + 1} defines global names {bad}; use _private names (marimo)")
        out.append(md_cell(f"## Step {i + 1}: {c['title']}\n\n{c['md'].strip()}"))
        out.append(cell(code, ["INPUTS", "cases", "report"], []))
    out.append('if __name__ == "__main__":\n    app.run()\n')
    return "".join(out)


if __name__ == "__main__":
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "notebook", "ai_failure_modes_molab.py")
    with open(dst, "w", encoding="utf-8") as f:
        f.write(generate())
    print("wrote", dst)
