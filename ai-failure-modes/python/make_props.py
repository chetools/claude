"""Generate python/props_data.py: saturation tables computed with CoolProp (reference
equations of state: IAPWS-95 for water, Lemmon et al. for propane, Span-Wagner for CO2).

    python make_props.py

The page runs in Pyodide without CoolProp, so it interpolates these tables instead.
test_cases.py checks the interpolation against CoolProp at points between the nodes.
"""
import os

from CoolProp.CoolProp import PropsSI

HERE = os.path.dirname(os.path.abspath(__file__))
R = 8.314462618  # J/(mol K)


def water_table():
    """Rows (T [K], rho_liq [kg/m3], h_liq [kJ/kg], h_vap [kJ/kg], rho_vap [kg/m3]) at saturation, 1 K steps."""
    rows = []
    for T in range(274, 621):
        rows.append((float(T), PropsSI("D", "T", T, "Q", 0, "Water"), PropsSI("H", "T", T, "Q", 0, "Water") / 1e3,
                     PropsSI("H", "T", T, "Q", 1, "Water") / 1e3, PropsSI("D", "T", T, "Q", 1, "Water")))
    return rows


def propane_table():
    """Rows (P [bar abs], T_sat [K], latent heat [kJ/kg], Z of sat. vapour [-], ideal-gas k = cp0/cv0 at T_sat [-])."""
    M = PropsSI("M", "Propane")  # kg/mol
    rows = []
    for i in range(1, 81):
        P = 0.5 * i * 1e5
        if P > 41.0e5:
            break
        T = PropsSI("T", "P", P, "Q", 1, "Propane")
        lam = (PropsSI("H", "P", P, "Q", 1, "Propane") - PropsSI("H", "P", P, "Q", 0, "Propane")) / 1e3
        Z = PropsSI("Z", "P", P, "Q", 1, "Propane")
        cp0 = PropsSI("CP0MASS", "P", P, "Q", 1, "Propane")
        k = cp0 / (cp0 - R / M)
        rows.append((P / 1e5, T, lam, Z, k))
    return rows


def co2_reference():
    """Rows (T [K], P [bar], rho [kg/m3]) for CO2 from the Span-Wagner EOS (CoolProp), for the PR comparison table."""
    rows = []
    for T in (290.0, 310.0, 330.0, 373.15):
        for P in (10.0, 50.0, 80.0, 100.0, 150.0):
            rows.append((T, P, PropsSI("D", "T", T, "P", P * 1e5, "CO2")))
    return rows


def main():
    w, p, c = water_table(), propane_table(), co2_reference()
    fmt = lambda rows: "[\n" + "".join("    (" + ", ".join(f"{v:.10g}" for v in r) + "),\n" for r in rows) + "]"
    src = ('"""Saturation tables generated by make_props.py from CoolProp ' + "(do not edit).\n\n"
           "WATER: (T [K], rho_liq [kg/m3], h_liq [kJ/kg], h_vap [kJ/kg], rho_vap [kg/m3]) at saturation.\n"
           "PROPANE: (P [bar abs], T_sat [K], latent heat [kJ/kg], Z sat. vapour [-], ideal-gas cp0/cv0 [-]).\n"
           "CO2_REF: (T [K], P [bar], rho [kg/m3]) from the Span-Wagner equation of state.\n" + '"""\n'
           f"WATER = {fmt(w)}\n\nPROPANE = {fmt(p)}\n\nCO2_REF = {fmt(c)}\n")
    with open(os.path.join(HERE, "props_data.py"), "w") as f:
        f.write(src)
    print(f"props_data.py: {len(w)} water rows, {len(p)} propane rows, {len(c)} CO2 rows")


if __name__ == "__main__":
    main()
