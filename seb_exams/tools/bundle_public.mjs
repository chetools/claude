// Bundles worker/public/** into worker/src/public_files.js (generated, gitignored), so the teacher app is
// served from the Worker code itself. Wrangler's static-asset upload does not get through this environment's
// proxy, and the app is small. Also copies the AI guide and example zip into worker/public/docs/ first.
//   node tools/bundle_public.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PUB = path.join(ROOT, "worker/public");
fs.mkdirSync(path.join(PUB, "docs"), { recursive: true });
fs.copyFileSync(path.join(ROOT, "docs/AI_EXAM_GUIDE.md"), path.join(PUB, "docs/AI_EXAM_GUIDE.md"));
fs.copyFileSync(path.join(ROOT, "examples/example-exam.zip"), path.join(PUB, "docs/example-exam.zip"));

const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".md": "text/markdown; charset=utf-8", ".zip": "application/zip", ".svg": "image/svg+xml", ".png": "image/png" };
const files = {};
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const f = path.join(dir, e.name);
    if (e.isDirectory()) { walk(f); continue; }
    const type = TYPES[path.extname(e.name)];
    if (!type) throw new Error("bundle_public: no content type for " + f);
    files["/" + path.relative(PUB, f).split(path.sep).join("/")] = { type, b64: fs.readFileSync(f).toString("base64") };
  }
})(PUB);
if (!files["/index.html"]) throw new Error("bundle_public: worker/public/index.html missing");
fs.writeFileSync(path.join(ROOT, "worker/src/public_files.js"),
  "// GENERATED by tools/bundle_public.mjs from worker/public/ - do not edit.\nexport const FILES = " + JSON.stringify(files) + ";\n");
console.log(`bundled ${Object.keys(files).length} files from worker/public`);
