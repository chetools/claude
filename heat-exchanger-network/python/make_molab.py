"""Generate the editable MoLab (marimo) notebook from the page's breakdown.

    python make_molab.py [OUT.py]

The notebook has the same steps, explanations and code as the Python tab of
the page (walkthrough.CELLS), so the page and the notebook cannot drift apart.
MoLab opens a single file from GitHub with no repository checkout, so hen.py
is embedded in the setup cell.

marimo requires that each global name is defined in exactly one cell;
check_unique() enforces that on walkthrough.CELLS (build.py calls it).
"""
import ast
import os
import re
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import walkthrough  # noqa: E402

PAGE_URL = "https://chetools.github.io/claude/heat-exchanger-network/"
SETUP_NAMES = {"mo", "go", "hen", "make_fig"}
SETUP_IMPORTS = {"import hen"}


class _Defs(ast.NodeVisitor):
    """Global names a cell defines (marimo semantics): top-level assignments,
    loop targets, imports, def/class names -- not names inside functions,
    lambdas or comprehensions, and not _private names."""

    def __init__(self):
        self.names = set()

    def visit_Name(self, node):
        if isinstance(node.ctx, ast.Store) and not node.id.startswith("_"):
            self.names.add(node.id)

    def visit_Import(self, node):
        for a in node.names:
            n = (a.asname or a.name).split(".")[0]
            if not n.startswith("_"):
                self.names.add(n)

    visit_ImportFrom = visit_Import

    def visit_FunctionDef(self, node):
        if not node.name.startswith("_"):
            self.names.add(node.name)

    visit_ClassDef = visit_FunctionDef

    def _skip(self, node):
        pass

    visit_Lambda = visit_ListComp = visit_SetComp = visit_DictComp = visit_GeneratorExp = _skip


def defs_of(code):
    v = _Defs()
    v.visit(ast.parse(code))
    return v.names


def loads_of(code):
    return {n.id for n in ast.walk(ast.parse(code)) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)}


def check_unique(cells):
    """Raise if two cells define the same global (marimo would refuse)."""
    seen = {}
    for i, c in enumerate(cells):
        for n in defs_of(strip_setup(c["code"])):
            if n in seen or n in SETUP_NAMES | {"USER_INPUTS"}:
                raise ValueError(f"name {n!r} is defined in step {seen.get(n, 0) + 1} and step {i + 1}; "
                                 "marimo needs one definition per name")
            seen[n] = i


def strip_setup(code):
    return "\n".join(l for l in code.strip("\n").splitlines() if l.strip() not in SETUP_IMPORTS).strip("\n")


def convert_figures(code):
    """Top-level figure(...) calls -> _figN = make_fig(...); returns (code, names)."""
    names = []

    def sub(m):
        names.append(f"_fig{len(names) + 1}")
        return f"{names[-1]} = make_fig("

    return re.sub(r"(?m)^figure\(", sub, code), names


def cell(body, args, returns):
    sig = ", ".join(sorted(args))
    ret = "return" if not returns else "return (" + ", ".join(sorted(returns)) + ",)"
    return f"@app.cell\ndef _({sig}):\n{textwrap.indent(body, '    ')}\n    {ret}\n\n\n"


def md_cell(text):
    assert '"""' not in text
    return cell(f'mo.md(r"""\n{text.strip()}\n""")', ["mo"], [])


INPUTS = """# Inputs (the page's sidebar).  Edit and re-run: every downstream cell recomputes.
# Leave a key out to keep the case's own data.
USER_INPUTS = dict(
    case={case!r},
    # other cases: {others}
    emat=None,             # minimum approach temperature [K]; None = the case's value
    stages=None,           # stages of the superstructure; None = max(hot, cold streams)
    # cost law: kind "paper" (benchmarks only), "seider" or "turton"
    law=dict(kind="seider", cepci=800.0,     # CEPCI: placeholder, enter the current value
             rate=0.10, years=10,            # annualisation: capital recovery factor
             type="floating head", tube_ft=20, p_psig=150.0, p_barg=10.0),
    prices=dict(fuel=3.48, elec=0.0903, co2=0.0, hours=8000.0),   # see hen.DEFAULT_PRICES
    forbid=None,           # nH x nC booleans; None = the case's forbidden matches
)"""


def generate():
    import hen
    src = open(os.path.join(HERE, "hen.py"), encoding="utf-8").read()
    assert "'''" not in src
    cells = walkthrough.CELLS
    check_unique(cells)
    out = ['# /// script\n# requires-python = ">=3.10"\n'
           '# dependencies = ["marimo", "numpy", "scipy", "plotly"]\n# ///\n\n'
           '"""Heat exchanger network synthesis: the Python reference, step by step.\n\n'
           "Editable companion to " + PAGE_URL + "\n"
           "GENERATED by heat-exchanger-network/python/make_molab.py from walkthrough.py and hen.py;\n"
           "edit those files, not this one.  Self-contained (hen.py is embedded) because MoLab\n"
           'opens a single file from GitHub with no repository checkout.\n"""\n\n'
           "import marimo\n\n__generated_with = \"0.25.2\"\napp = marimo.App(width=\"medium\")\n\n\n"]
    out.append(md_cell(f"""
# Heat exchanger network synthesis, step by step

Editable companion to the [interactive page]({PAGE_URL}). Each step explains one piece of the
synthesis (utility prices, exchanger costs with materials, LP targets with forbidden matches, MILP
for the fewest matches, the stage-wise NLP for the loads, and simulated annealing over the
topology), runs it, and shows the result. The page's *Python (step by step)* tab has the same code
and explanations.

**To run:** once the notebook has loaded, run all cells. **To experiment:** edit `USER_INPUTS` below
and re-run; every cell that depends on it recomputes.

The reference module `hen` is embedded in the next cell. Costs are study-level estimates
(expect roughly ±30-50 %), not vendor quotes.
"""))
    setup = ("# Setup: the reference module hen (embedded source of python/hen.py) and\n"
             "# make_fig() to turn the plain trace dicts used below into Plotly figures.\n"
             "import sys as _sys\nimport types as _types\n\n"
             "import marimo as mo\nimport plotly.graph_objects as go\n\n"
             f"_HEN_SOURCE = r'''{src}'''\n\n"
             'hen = _types.ModuleType("hen")\n'
             "exec(compile(_HEN_SOURCE, \"hen.py\", \"exec\"), hen.__dict__)\n"
             '_sys.modules["hen"] = hen   # so "import hen" also works in your own cells\n\n\n'
             "def make_fig(traces, **layout):\n"
             '    """Plotly figure from trace dicts and layout keywords."""\n'
             "    layout.setdefault(\"height\", 380)\n"
             "    return go.Figure(dict(data=traces, layout=layout))")
    out.append(cell(setup, [], sorted(SETUP_NAMES)))
    others = "; ".join(n for n in list(hen.ILLUSTRATIVE) + list(hen.BENCHMARKS) if n != hen.DEFAULT_CASE)
    out.append(cell(INPUTS.format(case=hen.DEFAULT_CASE, others=others), [], ["USER_INPUTS"]))
    defined = set(SETUP_NAMES) | {"USER_INPUTS"}
    for i, c in enumerate(cells):
        out.append(md_cell(f"## Step {i + 1}: {c['title']}\n\n{c['md'].strip()}"))
        code = strip_setup(c["code"])
        code, figs = convert_figures(code)
        d = defs_of(code)
        args = (loads_of(code) & defined) - d
        if figs:
            args |= {"make_fig"}
            code += "\n" + (figs[0] if len(figs) == 1 else f"mo.vstack([{', '.join(figs)}])")
            if len(figs) > 1:
                args |= {"mo"}
        out.append(cell(code, args, d))
        defined |= d
    out.append('if __name__ == "__main__":\n    app.run()\n')
    return "".join(out)


if __name__ == "__main__":
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "notebook", "walkthrough_molab.py")
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(generate())
    print("wrote", dst)
