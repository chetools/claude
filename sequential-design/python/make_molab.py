"""Generate the editable MoLab (marimo) notebook from the page's breakdown.

    python make_molab.py [OUT.py]

The notebook has the same steps, explanations and code as the Python tab of
the page (walkthrough.CELLS), so the two cannot drift apart.  MoLab opens a
single file from GitHub with no repository checkout, so sdl.py is embedded in
the setup cell.  marimo requires each global name to be defined in exactly
one cell; check_unique() enforces that on walkthrough.CELLS.
"""
import ast
import os
import re
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import walkthrough  # noqa: E402

PAGE_URL = "https://chetools.github.io/claude/sequential-design/"
SETUP_NAMES = {"mo", "np", "go", "sdl", "make_fig"}
SETUP_IMPORTS = {"import numpy as np", "import sdl"}

INPUT_DOCS = {
    "truth": "true process: forrester, gramacy_lee, reactor_1d (1-D); branin, inert, reactor_2d (2-D)",
    "strategy": "random, lhs, maxvar or imse (used by the App; step 8 runs all four)",
    "n0": "runs in the initial design",
    "batch": "runs per batch",
    "budget": "total runs",
    "noise_pct": "measurement noise, % of the standard deviation of the true function",
    "seed": "random seed (design and noise)",
}


class _Defs(ast.NodeVisitor):
    """Global names a cell defines (marimo semantics): top-level assignments,
    loop targets, imports, def/class names -- not names inside functions,
    lambdas or comprehensions, and not _private names."""

    def __init__(self):
        self.names = set()

    def visit_Name(self, node):
        if isinstance(node.ctx, ast.Store) and not node.id.startswith("_"):
            self.names.add(node.id)

    def visit_Import(self, node):
        for a in node.names:
            n = (a.asname or a.name).split(".")[0]
            if not n.startswith("_"):
                self.names.add(n)

    visit_ImportFrom = visit_Import

    def visit_FunctionDef(self, node):
        if not node.name.startswith("_"):
            self.names.add(node.name)

    visit_ClassDef = visit_FunctionDef

    def _skip(self, node):
        pass

    visit_Lambda = visit_ListComp = visit_SetComp = visit_DictComp = visit_GeneratorExp = _skip


def defs_of(code):
    v = _Defs()
    v.visit(ast.parse(code))
    return v.names


def loads_of(code):
    return {n.id for n in ast.walk(ast.parse(code)) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)}


def check_unique(cells):
    """Raise if two cells define the same global (marimo would refuse)."""
    seen = {}
    for i, c in enumerate(cells):
        for n in defs_of(strip_setup(c["code"])):
            if n in seen or n in SETUP_NAMES | {"USER_INPUTS"}:
                raise ValueError(f"name {n!r} is defined in step {seen.get(n, 0) + 1} and step {i + 1}; "
                                 "marimo needs one definition per name")
            seen[n] = i


def strip_setup(code):
    return "\n".join(l for l in code.strip("\n").splitlines() if l.strip() not in SETUP_IMPORTS).strip("\n")


def convert_figures(code):
    """figure(...) calls (also inside if/for blocks) -> collected into _figs and
    shown with mo.vstack at the end of the cell.  Returns (code, has_figures)."""
    if not re.search(r"(?m)^\s*figure\(", code):
        return code, False
    code = re.sub(r"(?m)^(\s*)figure\(", r"\1_show(", code)
    pre = "_figs = []\n_show = lambda traces, **layout: _figs.append(make_fig(traces, **layout))\n"
    return pre + code + "\nmo.vstack(_figs)", True


def cell(body, args, returns):
    sig = ", ".join(sorted(args))
    ret = "return" if not returns else "return (" + ", ".join(sorted(returns)) + ",)"
    return f"@app.cell\ndef _({sig}):\n{textwrap.indent(body, '    ')}\n    {ret}\n\n\n"


def md_cell(text):
    assert '"""' not in text
    return cell(f'mo.md(r"""\n{text.strip()}\n""")', ["mo"], [])


def generate():
    sdl_src = open(os.path.join(HERE, "sdl.py"), encoding="utf-8").read()
    assert "'''" not in sdl_src
    cells = walkthrough.CELLS
    check_unique(cells)

    out = ['# /// script\n# requires-python = ">=3.10"\n'
           '# dependencies = ["marimo", "numpy", "plotly"]\n# ///\n\n'
           '"""Sequential design of experiments for a global model: the Python reference, step by step.\n\n'
           "Editable companion to " + PAGE_URL + "\n"
           "GENERATED by sequential-design/python/make_molab.py from walkthrough.py and sdl.py;\n"
           "edit those files, not this one.  Self-contained (sdl.py is embedded) because MoLab\n"
           'opens a single file from GitHub with no repository checkout.\n"""\n\n'
           "import marimo\n\n__generated_with = \"0.25.2\"\napp = marimo.App(width=\"medium\")\n\n\n"]

    out.append(md_cell(f"""
# Sequential design of experiments, step by step

Editable companion to the [interactive page]({PAGE_URL}). Each step explains one piece of sequential
design for a global model (a Gaussian process fitted to noisy runs, and four ways to choose the next runs),
runs it, and shows the result. The page's *Python (step by step)* tab has the same steps and code.

**To run:** once the notebook has loaded, run all cells (command palette → "Re-run all cells", or the
run button). **To experiment:** edit a value in the `USER_INPUTS` cell below and re-run; every cell
that depends on it recomputes.

The reference module `sdl` is embedded in the next cell; the page's *sdl.py (full source)* tab has a
highlighted listing.
"""))

    setup = ("# Setup: libraries, the reference module sdl (embedded source of python/sdl.py),\n"
             "# and make_fig() to turn the plain trace dicts used below into Plotly figures.\n"
             "import sys as _sys\nimport types as _types\n\n"
             "import marimo as mo\nimport numpy as np\nimport plotly.graph_objects as go\n\n"
             f"_SDL_SOURCE = r'''{sdl_src}'''\n\n"
             'sdl = _types.ModuleType("sdl")\n'
             "exec(compile(_SDL_SOURCE, \"sdl.py\", \"exec\"), sdl.__dict__)\n"
             '_sys.modules["sdl"] = sdl   # so "import sdl" also works in your own cells\n\n\n'
             "def make_fig(traces, **layout):\n"
             '    """Plotly figure from trace dicts and layout keywords."""\n'
             "    layout.setdefault(\"height\", 400)\n"
             "    return go.Figure(dict(data=traces, layout=layout))")
    out.append(cell(setup, [], sorted(SETUP_NAMES)))

    lines = ["# Inputs (the page's defaults).  Edit a value and re-run: every downstream cell recomputes.",
             "USER_INPUTS = dict("]
    for k, v in walkthrough.DEFAULT_INPUTS.items():
        lines.append(f"    {k}={v!r},  # {INPUT_DOCS[k]}")
    lines.append(")")
    out.append(cell("\n".join(lines), [], ["USER_INPUTS"]))

    defined = set(SETUP_NAMES) | {"USER_INPUTS"}
    for i, c in enumerate(cells):
        out.append(md_cell(f"## Step {i + 1}: {c['title']}\n\n{c['md'].strip()}"))
        code = strip_setup(c["code"])
        code, figs = convert_figures(code)
        d = defs_of(code)
        args = (loads_of(code) & defined) - d
        if figs:
            args |= {"make_fig", "mo"}
        out.append(cell(code, args, d))
        defined |= d

    out.append('if __name__ == "__main__":\n    app.run()\n')
    return "".join(out)


if __name__ == "__main__":
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "notebook", "walkthrough_molab.py")
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(generate())
    print("wrote", dst)
