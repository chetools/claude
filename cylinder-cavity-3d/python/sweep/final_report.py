"""Write notes/results_final.md from the final runs in sweep/results_final (LBM, final code, fluid-only
diagnostics).  Every number the page quotes about the sweep comes from this report.

    python sweep/final_report.py
"""
import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results_final")
OUT = os.path.join(HERE, "..", "..", "notes", "results_final.md")


def load(name):
    f = os.path.join(RES, name + ".json")
    if not os.path.isfile(f):
        return None
    r = json.load(open(f))
    s = {k: np.array(v, dtype=float) if k != "Ekz" else v for k, v in r["series"].items()}
    return r, s


def growth(s, lo=1e-7, hi=1e-3, t0=1.0):
    """Growth rate sigma from ln E3d = 2 sigma t + c, fitted where lo < E3d/E < hi and t >= t0."""
    t, E, E3 = s["t"], s["E"], s["E3d"]
    m = (E3 / E > lo) & (E3 / E < hi) & (t >= t0)
    if m.sum() < 5:
        return None, None
    return float(np.polyfit(t[m], np.log(E3[m]), 1)[0] / 2), (float(t[m].min()), float(t[m].max()))


def late_mean(s, k, frac=0.5):
    t = s["t"]
    return float(np.mean(s[k][t >= frac * t[-1]]))


def first_apart(s3, s2, k, tol=0.05, t0=0.5):
    t = s3["t"]
    y = np.interp(t, s2["t"], s2[k])
    rel = np.abs(s3[k] - y) / np.maximum(np.abs(y), 1e-300)
    sm = np.convolve(rel, np.ones(5) / 5, mode="same")
    bad = (sm > tol) & (t >= t0)
    return float(t[np.argmax(bad)]) if bad.any() else None


def fmt(x, f="{:.3g}"):
    return "–" if x is None else f.format(x)


def fv_crosscheck():
    """Finite-volume runs of the same cases (sweep/fv_growth.py -> results_fv/), compared with the LBM runs."""
    fvdir = os.path.join(HERE, "results_fv")
    out = []
    for n in sorted(os.path.basename(f)[:-5] for f in glob.glob(os.path.join(fvdir, "*.json"))):
        if n.endswith("_2d") or not os.path.isfile(os.path.join(fvdir, n + "_2d.json")) or load(n) is None:
            continue
        rows = json.load(open(os.path.join(fvdir, n + ".json")))["rows"]
        rows2 = json.load(open(os.path.join(fvdir, n + "_2d.json")))["rows"]
        f3 = {k: np.array([r[k] for r in rows], float) for k in ("t", "E", "Z", "E3d", "torque")}
        f2 = {k: np.array([r[k] for r in rows2], float) for k in ("t", "E", "Z", "torque")}
        _, l3 = load(n)
        _, l2 = load(n + "_2d")
        if not out:
            out = ["## Cross-check with the finite-volume solver", "",
                   "Same case run with `fv3d.py` (inner-ramp mask, N = 64, N_z = 32 and N_z = 1), late means over "
                   "t = 10–20. The two methods treat the cylinder surface differently (sharp interpolated "
                   "bounce-back vs a one-cell mask), which mostly affects the enstrophy of the cells next to it.",
                   "", "| case | quantity | LBM 3D/2D | FV 3D/2D | LBM 3D | FV 3D |", "|---|---|---|---|---|---|"]
        sl, wl = growth(l3)
        sf, wf = growth(f3)
        out.append(f"| {n} | growth rate σ | | | {fmt(sl, '{:+.3f}')} | {fmt(sf, '{:+.3f}')} |")
        for k, lab in (("E", "kinetic energy E"), ("Z", "enstrophy Z"), ("torque", "torque")):
            lm3, lm2 = late_mean(l3, k), late_mean(l2, k)
            fm3, fm2 = (float(np.mean(d[k][d["t"] >= 10])) for d in (f3, f2))
            out.append(f"| {n} | {lab} | {lm3 / lm2:.3g} | {fm3 / fm2:.3g} | {lm3:.4g} | {fm3:.4g} |")
        out.append(f"| {n} | E3d/E late | | | {late_mean(l3, 'E3d') / late_mean(l3, 'E'):.3g} | "
                   f"{np.mean(f3['E3d'][f3['t'] >= 10]) / np.mean(f3['E'][f3['t'] >= 10]):.3g} |")
    return out + [""] if out else []


def main():
    lines = ["# Final runs (LBM, final code, fluid-only diagnostics)", "",
             "Generated by `python/sweep/final_report.py` from `python/sweep/results_final/`. Grid N = 64, "
             "N_z = 32 (L_z = 0.5) unless stated; R = 0.1, r_o = 0.2, seed amplitude 1e-3; regularised "
             "collision. Each 3D run has a 2D baseline (same inputs, N_z = 1). Late means are over the second "
             "half of the run (t = 10–20). Torque is per unit span on the cylinder.", ""]
    names = sorted({os.path.basename(f)[:-5] for f in glob.glob(os.path.join(RES, "*.json"))})
    three = [n for n in names if not n.endswith("_2d")]
    lines += ["## Growth of the spanwise perturbation", "",
              "| run | Re | span | U_s | U_o | t_end | σ (fit window) | σ late (t ≥ t_end/3) | E3d/E late | E_w/E late | dominant k_z |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for n in three:
        r, s = load(n)
        c = r["params"] if "params" in r else r["case"]
        sig, win = growth(s)
        ek = s.get("Ekz")
        kz = "–"
        if ek and ek[0] is not None and ek[0][1] is not None:
            a = np.array(ek, float)[s["t"] >= 0.75 * s["t"][-1]][:, 1:]
            kz = str(int(np.argmax(a.mean(axis=0)) + 1))
        tl = s["t"] >= s["t"][-1] / 3
        late_sig = float(np.polyfit(s["t"][tl], np.log(s["E3d"][tl]), 1)[0] / 2) if np.all(s["E3d"][tl] > 0) else None
        lines.append(f"| {n} | {c['Re']:g} | {c['span']} | {c['Us']:g} | {c['Uo']:g} | {s['t'][-1]:g} | "
                     f"{fmt(sig, '{:+.3f}')}{'' if win is None else f' ({win[0]:.1f}–{win[1]:.1f})'} | "
                     f"{'–' if c['span'] != 'periodic' else (fmt(late_sig, '{:+.3f}') if s['E3d'][-1] / s['E'][-1] < 1e-3 else '(saturated)')} | "
                     f"{late_mean(s, 'E3d') / late_mean(s, 'E'):.3g} | {late_mean(s, 'Ew') / late_mean(s, 'E'):.3g} | {kz} |")
    lines += ["", "σ is the growth rate of the perturbation amplitude: E3d ∝ e^{2σt} while E3d/E is between "
              "1e-7 and 1e-3 (t ≥ 1). A negative σ means the seed decays. σ late is fitted over the last two thirds "
              "of the run while the perturbation is still small (E3d/E < 1e-3 at the end); it separates a slow "
              "growth from the decay of the initial transient near onset.", "",
              "## 3D against the 2D baseline", "",
              "| run | quantity | 3D late mean | 2D late mean | 3D / 2D | first > 5 % apart at t |",
              "|---|---|---|---|---|---|"]
    for n in three:
        b = load(n + "_2d")
        if b is None:
            continue
        _, s3 = load(n)
        _, s2 = b
        for k, lab in (("E", "kinetic energy E"), ("Z", "enstrophy Z"), ("torque", "torque")):
            x, y = late_mean(s3, k), late_mean(s2, k)
            lines.append(f"| {n} | {lab} | {x:.4g} | {y:.4g} | {x / y:.3g} | {fmt(first_apart(s3, s2, k), '{:.1f}')} |")
    lines += ["", "\"First > 5 % apart\": first time t ≥ 0.5 where the 5-sample running mean of |3D − 2D|/|2D| "
              "exceeds 0.05 (both runs start from rest, so earlier relative differences are meaningless). "
              "Torque samples are single-step values every 0.1 time units; their late means average ~100 samples.",
              ""]
    lines += fv_crosscheck()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
